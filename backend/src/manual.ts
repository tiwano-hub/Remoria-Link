import {
  NAV,
  CASE_STATUS_LABEL,
  PURCHASE_METHOD_LABEL,
  ROLE_LABEL,
  INVENTORY_STATUS_LABEL,
} from './constants';

/**
 * 使い方マニュアル本文を生成する。
 * 画面構成・ステータス・権限などは constants.ts から動的に差し込むため、
 * 仕様（メニューやステータス）を変更すると本マニュアルも自動で書き換わる。
 * 操作手順などの説明文を変えたいときは、このファイルの該当箇所を編集する。
 */
export function buildManualMarkdown(): string {
  const labelTable = (title: string, obj: Record<string, string>) =>
    `### ${title}\n\n` +
    '| コード | 表示名 |\n| --- | --- |\n' +
    Object.entries(obj).map(([k, v]) => `| ${k} | ${v} |`).join('\n') +
    '\n';

  const navSection = NAV.map((g) =>
    `### ${g.group}\n\n` +
    g.items.map((it) => `- **${it.label}** — ${it.desc}`).join('\n') +
    '\n',
  ).join('\n');

  return `# Remoria Link 使い方マニュアル

Remoria Link は出張買取の業務（案件管理・在庫・販売・入出金・領収書・契約書）を一元管理するシステムです。スマートフォンでの利用に最適化されています。

> このマニュアルはアプリの最新の仕様（メニュー・ステータス・権限）を自動で反映します。

---

## 1. 基本操作

- **メニュー**：画面左上の「☰」ボタンでメニューを開きます。背景をタップすると閉じます。
- **保存**：多くの入力欄は、入力してEnterを押すか、別の場所をタップ（フォーカスを外す）すると自動保存されます。
- **ログアウト**：画面右上の「ログアウト」ボタンから。

## 2. 画面（メニュー）一覧

${navSection}

---

## 3. 案件の流れ（基本フロー）

1. **電話番号入力**：かかってきた電話番号を入力し、既存顧客か確認します。
2. **案件登録**：顧客名（苗字カナ・名カナ）と電話番号を入力して案件を作成します。ステータスを「予約中」にすると予約日が自動で記録されます。
3. **案件詳細**：担当者・査定日・査定時間・作業日・作業時間などを入力します。各項目はその場で編集・保存できます。
4. **買取品明細**：商品名・数量・グレード・買取金額などを登録します。「＋行を追加」で複数商品をまとめて入力できます。登録済みの明細も後から編集できます。
5. **契約書作成**：契約書を作成し、顧客にURLを送付します。顧客は契約書画面で漢字氏名を入力し、本人確認・署名を行います。
6. **領収書発行**：必要に応じてインボイス対応の電子領収書を発行します。
7. **在庫登録**：「買取品を在庫登録」で、買取品を在庫に取り込みます。
8. **販売・入出金**：販売実績や振込・現金精算を記録します。

## 4. 顧客名の扱い

- スタッフが登録するのは **苗字（カナ）** と **名（カナ）** のみです。
- **漢字氏名は、確認用契約書を受け取った顧客本人が入力**します。入力された漢字は顧客情報・契約書に自動反映されます。

## 5. 各種区分（コード一覧）

${labelTable('案件ステータス', CASE_STATUS_LABEL)}
${labelTable('買取方法', PURCHASE_METHOD_LABEL)}
${labelTable('在庫ステータス', INVENTORY_STATUS_LABEL)}
${labelTable('ユーザー権限', ROLE_LABEL)}

---

## 6. データの取り出し（CSV）

「使い方・AIサポート」画面の「データ出力」タブから、案件・顧客・在庫・販売・入出金・領収書・ユーザー・操作ログを **CSV** で書き出せます。CSVはExcelでそのまま開けます（文字化けしないUTF-8形式）。

## 7. AIサポート

「AIチャット」タブで、操作方法や仕様について日本語で質問できます。回答はこのマニュアルの内容に基づきます。
`;
}
